        $agentChoice = Read-Host "Enter choice (1/2)"
        
        if ($agentChoice -eq "1") {
            $module = "NeoCare-AI"
            $defaultRoom = "R2"
            $defaultPatient = "P001"
        } elseif ($agentChoice -eq "2") {
            $module = "GeriCare-AI"
            $defaultRoom = "R5"
            $defaultPatient = "P002"
        } else {
            Write-Host "❌ Invalid choice" -ForegroundColor Red
            Read-Host "Press Enter to exit"
