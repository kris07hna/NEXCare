                try {
                    New-NetFirewallRule -DisplayName "NEXCARE Server" `
                                       -Direction Inbound `
                                       -LocalPort 3000 `
                                       -Protocol TCP `
                                       -Action Allow `
                                       -ErrorAction Stop | Out-Null
                    Write-Host "✅ Firewall rule added!" -ForegroundColor Green
                } catch {
                    Write-Host "❌ Failed to add firewall rule (need admin privileges)" -ForegroundColor Red
                    Write-Host "   Run PowerShell as Administrator and use:" -ForegroundColor Yellow
                    Write-Host "   New-NetFirewallRule -DisplayName 'NEXCARE Server' -Direction Inbound -LocalPort 3000 -Protocol TCP -Action Allow" -ForegroundColor White
                }
            }
        } else {
            Write-Host "✅ Firewall rule already exists" -ForegroundColor Green
        }
        
