        Write-Host "Checking Windows Firewall..." -ForegroundColor Yellow
        $firewallRule = Get-NetFirewallRule -DisplayName "NEXCARE Server" -ErrorAction SilentlyContinue
        
        if (-not $firewallRule) {
            Write-Host "⚠️  Firewall rule not found!" -ForegroundColor Yellow
            Write-Host "   Other laptops may not be able to connect." -ForegroundColor Yellow
            Write-Host ""
            $addFirewall = Read-Host "Add firewall rule? (requires admin) [Y/n]"
            
