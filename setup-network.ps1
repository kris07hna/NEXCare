# Server IP: $serverIP

NEXT_PUBLIC_API_URL=http://$serverIP:3000
NEXT_PUBLIC_SIGNALING_SERVER_URL=http://$serverIP:3000
NEXT_PUBLIC_OFFLINE_MODE=true

# Database
DATABASE_URL=file:./data/edgecare.db
"@ | Out-File -FilePath ".env.local" -Encoding UTF8
            Write-Host "✅ Created .env.local" -ForegroundColor Green
        } else {
            Write-Host "⚠️  .env.local already exists, updating URLs..." -ForegroundColor Yellow
            $envContent = @"
# Auto-generated by setup-network.ps1
# Server IP: $serverIP
# Updated: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")

NEXT_PUBLIC_API_URL=http://$serverIP:3000
NEXT_PUBLIC_SIGNALING_SERVER_URL=http://$serverIP:3000
NEXT_PUBLIC_OFFLINE_MODE=true

# Database
DATABASE_URL=file:./data/edgecare.db
"@
